@app.cell
def _(go, make_subplots, mo, nn, np, optim, torch):
    # Generate 2D continuous non-linear telemetry dataset (concentric ring / curved manifold)
    np.random.seed(42)
    torch.manual_seed(42)

    n_nominal = 600
    # Two correlated non-linear arms
    theta_pts = np.random.uniform(0, 1.5 * np.pi, n_nominal)
    r_pts = 4.0 + np.random.normal(0, 0.35, n_nominal)
    x1_nom = r_pts * np.cos(theta_pts)
    x2_nom = r_pts * np.sin(theta_pts)
    X_nom = np.column_stack([x1_nom, x2_nom])

    # Inject diverse anomalies:
    # 1. Void / Hole Anomalies (points in the center of the ring where r ~ 0)
    n_void = 25
    x1_void = np.random.normal(0, 0.8, n_void)
    x2_void = np.random.normal(0, 0.8, n_void)
    X_void = np.column_stack([x1_void, x2_void])

    # 2. Outlier Radial Spikes (r >> 4.0)
    n_spike = 25
    theta_spikes = np.random.uniform(0, 2 * np.pi, n_spike)
    r_spikes = np.random.uniform(7.0, 9.5, n_spike)
    x1_spike = r_spikes * np.cos(theta_spikes)
    x2_spike = r_spikes * np.sin(theta_spikes)
    X_spike = np.column_stack([x1_spike, x2_spike])

    X_all = np.vstack([X_nom, X_void, X_spike])
    y_true = np.array([0] * n_nominal + [1] * (n_void + n_spike))

    # Standardization
    x_mean = np.mean(X_nom, axis=0)
    x_std = np.std(X_nom, axis=0)
    X_nom_norm = (X_nom - x_mean) / x_std
    X_all_norm = (X_all - x_mean) / x_std

    # PyTorch VAE for Anomaly Detection
    class AnomalyVAE(nn.Module):
        def __init__(self, in_dim=2, latent_dim=2):
            super().__init__()
            self.encoder = nn.Sequential(
                nn.Linear(in_dim, 32),
                nn.Tanh(),
                nn.Linear(32, 16),
                nn.Tanh(),
            )
            self.fc_mu = nn.Linear(16, latent_dim)
            self.fc_logvar = nn.Linear(16, latent_dim)

            self.decoder = nn.Sequential(
                nn.Linear(latent_dim, 16),
                nn.Tanh(),
                nn.Linear(16, 32),
                nn.Tanh(),
                nn.Linear(32, in_dim),
            )

        def encode(self, x):
            h = self.encoder(x)
            return self.fc_mu(h), self.fc_logvar(h)

        def reparameterize(self, mu, logvar):
            std = torch.exp(0.5 * logvar)
            eps = torch.randn_like(std)
            return mu + std * eps

        def decode(self, z):
            return self.decoder(z)

        def forward(self, x):
            mu, logvar = self.encode(x)
            z = self.reparameterize(mu, logvar)
            return self.decode(z), mu, logvar

    vae_model = AnomalyVAE(in_dim=2, latent_dim=2)
    optimizer = optim.Adam(vae_model.parameters(), lr=0.01)

    X_nom_t = torch.tensor(X_nom_norm, dtype=torch.float32)
    X_all_t = torch.tensor(X_all_norm, dtype=torch.float32)

    # Train exclusively on nominal in-control data
    vae_model.train()
    for _epoch in range(120):
        optimizer.zero_grad()
        rec, mu, logvar = vae_model(X_nom_t)
        recon_loss = nn.functional.mse_loss(rec, X_nom_t, reduction="sum") / len(X_nom_t)
        kl = -0.5 * torch.sum(1.0 + logvar - mu.pow(2) - logvar.exp()) / len(X_nom_t)
        loss = recon_loss + 0.2 * kl
        loss.backward()
        optimizer.step()

    # Compute Monte Carlo ELBO Anomaly Scores (L = 10 samples)
    vae_model.eval()
    with torch.no_grad():
        mu_all, logvar_all = vae_model.encode(X_all_t)
        kl_all = -0.5 * torch.sum(1.0 + logvar_all - mu_all.pow(2) - logvar_all.exp(), dim=1).numpy()

        L_samples = 10
        rec_losses = []
        for _ in range(L_samples):
            z_sample = vae_model.reparameterize(mu_all, logvar_all)
            rec_sample = vae_model.decode(z_sample)
            rec_losses.append(torch.sum((X_all_t - rec_sample) ** 2, dim=1).numpy())

        recon_nll_mean = np.mean(rec_losses, axis=0)
        total_elbo_score = recon_nll_mean + 0.2 * kl_all

    score_thresh = float(np.percentile(total_elbo_score[:n_nominal], 95.0))

    fig = make_subplots(
        rows=1,
        cols=2,
        subplot_titles=[
            "<b>Telemetry Space: Nominal vs Detected Anomalies</b>",
            "<b>Reconstruction NLL vs Latent KL Divergence</b>",
        ],
        horizontal_spacing=0.14,
    )

    # Panel 1: Scatter of telemetry
    nom_mask = y_true == 0
    anom_mask = y_true == 1

    fig.add_trace(
        go.Scatter(
            x=X_all[nom_mask, 0],
            y=X_all[nom_mask, 1],
            mode="markers",
            marker=dict(color="#1D4ED8", size=5, opacity=0.6),
            name="Nominal In-Control Data",
        ),
        row=1,
        col=1,
    )
    fig.add_trace(
        go.Scatter(
            x=X_all[anom_mask, 0],
            y=X_all[anom_mask, 1],
            mode="markers",
            marker=dict(color="#DC2626", size=8, symbol="x"),
            name="Injected Ground-Truth Anomalies",
        ),
        row=1,
        col=1,
    )

    # Highlight flagged anomalies
    flagged = total_elbo_score > score_thresh
    fig.add_trace(
        go.Scatter(
            x=X_all[flagged, 0],
            y=X_all[flagged, 1],
            mode="markers",
            marker=dict(size=12, line=dict(color="#DC2626", width=1.5), color="rgba(0,0,0,0)"),
            name=f"VAE Alert (ELBO > {score_thresh:.2f})",
        ),
        row=1,
        col=1,
    )

    # Panel 2: Decomposed Anomaly Components (Recon vs KL)
    fig.add_trace(
        go.Scatter(
            x=recon_nll_mean[nom_mask],
            y=kl_all[nom_mask],
            mode="markers",
            marker=dict(color="#1D4ED8", size=5, opacity=0.6),
            showlegend=False,
        ),
        row=1,
        col=2,
    )
    fig.add_trace(
        go.Scatter(
            x=recon_nll_mean[anom_mask],
            y=kl_all[anom_mask],
            mode="markers",
            marker=dict(color="#DC2626", size=8, symbol="x"),
            showlegend=False,
        ),
        row=1,
        col=2,
    )

    fig.update_xaxes(title_text="Sensor Channel 1", row=1, col=1)
    fig.update_yaxes(title_text="Sensor Channel 2", row=1, col=1)
    fig.update_xaxes(title_text="Reconstruction Error (Out-of-Manifold)", type="log", row=1, col=2)
    fig.update_yaxes(title_text="KL Divergence D_KL (Latent Shift)", type="log", row=1, col=2)

    fig.update_layout(
        template="plotly_white",
        height=520,
        margin=dict(l=40, r=40, t=70, b=50),
        legend=dict(orientation="h", yanchor="bottom", y=-0.28, xanchor="center", x=0.5),
    )

    viz = mo.ui.plotly(fig)
    return (
        AnomalyVAE,
        L_samples,
        X_all,
        X_all_norm,
        X_all_t,
        X_nom,
        X_nom_norm,
        X_nom_t,
        X_spike,
        X_void,
        anom_mask,
        fig,
        flagged,
        kl,
        kl_all,
        logvar,
        logvar_all,
        loss,
        mu,
        mu_all,
        n_nominal,
        n_spike,
        n_void,
        nom_mask,
        optimizer,
        r_pts,
        r_spikes,
        rec,
        rec_losses,
        rec_sample,
        recon_loss,
        recon_nll_mean,
        score_thresh,
        theta_pts,
        theta_spikes,
        total_elbo_score,
        vae_model,
        viz,
        x1_nom,
        x1_spike,
        x1_void,
        x2_nom,
        x2_spike,
        x2_void,
        x_mean,
        x_std,
        y_true,
        z_sample,
    )


